#!/usr/bin/env python3
"""Regenerate crates/tc-core/src/models/flux2_vae_bn.rs: the FLUX.2 VAE latent batch-norm
statistics, read (with HTTP range requests, ~1 KB) from the Apache-2.0 FLUX.2 [klein] 4B release.
Draw Things' VAE checkpoints do not contain them. Needs numpy."""
import json, struct, sys, urllib.request
import numpy as np

URL = "https://huggingface.co/black-forest-labs/FLUX.2-klein-4B/resolve/main/vae/diffusion_pytorch_model.safetensors"
OUT = "crates/tc-core/src/models/flux2_vae_bn.rs"


def fetch(start, end):
    req = urllib.request.Request(URL, headers={"Range": f"bytes={start}-{end}"})
    return urllib.request.urlopen(req).read()


def main():
    n = struct.unpack("<Q", fetch(0, 7))[0]
    header = json.loads(fetch(8, 7 + n))
    base = 8 + n

    def tensor(name):
        v = header[name]
        s, e = v["data_offsets"]
        b = fetch(base + s, base + e - 1)
        assert v["dtype"] == "BF16", v["dtype"]
        return (np.frombuffer(b, np.uint16).astype(np.uint32) << 16).view(np.float32)

    def fmt(a):
        items = [repr(float(x)) for x in a]
        return "\n".join("    " + ", ".join(items[i:i + 8]) + "," for i in range(0, len(items), 8))

    mean, var = tensor("bn.running_mean"), tensor("bn.running_var")
    src = f"""//! FLUX.2 VAE latent batch-norm statistics (`bn.running_mean`, `bn.running_var`, 128 patchified
//! channels), from `vae/diffusion_pytorch_model.safetensors` of the Apache-2.0
//! black-forest-labs/FLUX.2-klein-4B release. Draw Things' VAE checkpoints do not store them.
//! Generated by scripts/gen_vae_bn.py.

#![allow(clippy::excessive_precision)]

pub const RUNNING_MEAN: [f32; 128] = [
{fmt(mean)}
];

pub const RUNNING_VAR: [f32; 128] = [
{fmt(var)}
];
"""
    open(sys.argv[1] if len(sys.argv) > 1 else OUT, "w").write(src)


if __name__ == "__main__":
    main()
